"""Bundle landing/legal articles for the app. Run with --check in CI."""

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


class LegalMarkdown(HTMLParser):
    """Convert the legal pages' explicit HTML subset; reject unsupported markup."""

    def __init__(self):
        super().__init__()
        self.active = False
        self.parts = []
        self.lists = []
        self.href = None

    def handle_starttag(self, tag, attrs):
        if tag == 'article':
            self.active = True
            return
        if not self.active:
            return
        attrs = dict(attrs)
        if tag in ('header', 'div'):
            return
        if tag in ('h1', 'h2', 'h3'):
            self.parts.append('\n\n' + '#' * int(tag[1]) + ' ')
        elif tag in ('p', 'ul', 'ol'):
            self.parts.append('\n\n')
            if tag in ('ul', 'ol'):
                self.lists.append(0 if tag == 'ol' else None)
        elif tag == 'li':
            marker = '-'
            if self.lists[-1] is not None:
                self.lists[-1] += 1
                marker = f'{self.lists[-1]}.'
            self.parts.append('\n' + marker + ' ')
        elif tag == 'hr':
            self.parts.append('\n\n---\n\n')
        elif tag in ('strong', 'em', 'code'):
            self.parts.append({'strong': '**', 'em': '*', 'code': '`'}[tag])
        elif tag == 'a':
            self.href = attrs['href']
            if not self.href.startswith(('https://', 'mailto:')):
                raise ValueError(f'Legal links must be absolute: {self.href}')
            self.parts.append('[')
        else:
            raise ValueError(f'Unsupported legal HTML tag: {tag}')

    def handle_endtag(self, tag):
        if tag == 'article':
            self.active = False
        if not self.active:
            return
        if tag in ('strong', 'em', 'code'):
            self.parts.append({'strong': '**', 'em': '*', 'code': '`'}[tag])
        elif tag == 'a':
            self.parts.append(f']({self.href})')
        elif tag in ('ul', 'ol'):
            self.lists.pop()
            self.parts.append('\n\n')
        elif tag in ('p', 'h1', 'h2', 'h3'):
            self.parts.append('\n\n')

    def handle_data(self, data):
        if self.active:
            text = re.sub(r'\s+', ' ', data)
            if text.strip():
                self.parts.append(text)

    def markdown(self):
        text = ''.join(self.parts)
        text = re.sub(r' *\n *', '\n', text)
        return re.sub(r'\n{3,}', '\n\n', text).strip() + '\n'


def outputs():
    content = {}
    for key, filename in (
        ('privacy', 'privacy-policy.html'),
        ('terms', 'terms-and-conditions.html'),
    ):
        source = (ROOT / 'landing/legal' / filename).read_text()
        parser = LegalMarkdown()
        parser.feed(source)
        markdown = parser.markdown()
        if not markdown.startswith('# ') or not parser.parts or parser.lists:
            raise ValueError(f'Missing or incomplete legal article: {filename}')
        content[key] = markdown
    privacy = (ROOT / 'landing/legal/privacy-policy.html').read_text()
    article = privacy[privacy.index('<article>'):privacy.index('</article>') + len('</article>')]
    public_policy = f"""<!doctype html>
<!-- Generated by scripts/sync-legal.py from landing/legal/privacy-policy.html. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Privacy Policy · Active Next</title>
    <style>
      :root {{ font-family: system-ui, sans-serif; line-height: 1.65; color-scheme: light dark; }}
      main {{ max-width: 48rem; margin: auto; padding: 2rem 1.25rem; }}
      a {{ color: light-dark(#0058a8, #8fc6ff); }}
    </style>
  </head>
  <body>
    <main>
      {article}
    </main>
  </body>
</html>
"""
    return {
        ROOT / 'features/legal/legalContent.json': json.dumps(content, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'public/privacy-policy.html': public_policy,
    }


if __name__ == '__main__':
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--check', action='store_true')
    check = args.parse_args().check
    for path, expected in outputs().items():
        if check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit('Legal bundle is stale. Run: python3 scripts/sync-legal.py')
        else:
            path.write_text(expected)
    print('PASS: app legal bundle matches landing/legal.' if check else 'Updated app legal bundle.')
