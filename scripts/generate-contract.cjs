const fs = require('node:fs')
const { execFileSync } = require('node:child_process')
const { z } = require('zod')
const { requests } = require('../contracts/v1/request-contract.cjs')
const { responses, error } = require('../contracts/v1/response-contract.cjs')
const { operations } = require('../contracts/v1/release-operations.json')
const schema = value => z.toJSONSchema(value, { target: 'draft-2020-12', unrepresentable: 'any', io: 'input' })
const schemas = { Error: schema(error) }
const paths = {}
const metadata = {}
for (const operation of operations.filter(o => requests[o.id])) {
  const key = operation.id.replace(/\./g, '_')
  const request = requests[operation.id]
  for (const part of ['body', 'query', 'path']) schemas[`${key}_${part}`] = schema(request[part])
  schemas[`${key}_response`] = schema(responses[operation.id])
  const ordering = {
    'catalog.get': 'Items are ordered by sourceKey ascending.',
    'catalog.search': 'Items are ordered by sourceKey ascending.',
    'workout.list': 'Items are ordered by (createdAt, id) ascending.',
    'routine.list': 'Items are ordered by (createdAt, id) ascending.',
    'record.list': 'Items are ordered by (completedAt, id) descending.',
    'progression.logs': 'Items are ordered by the parent record (completedAt, id) descending; those keys are not present in this response and cannot be validated by the client.',
    'workout.delete': 'Routine versions are ordered by the routine (createdAt, id) ascending; createdAt is not present in this response and cannot be validated by the client.',
  }
  if (ordering[operation.id]) schemas[`${key}_response`].description = ordering[operation.id]
  let path = operation.path.split('?')[0]
  if (Object.keys(request.path.shape).length) {
    path = operation.id === 'progression.logs' ? '/api/exercises/{id}/logs' : path.replace(/\/[^/]+$/, '/{id}')
  }
  const parameters = ['path', 'query'].flatMap(part => {
    const json = schemas[`${key}_${part}`]
    return Object.entries(json.properties).map(([name, value]) => ({ name, in: part, required: part === 'path' || (json.required || []).includes(name), schema: value }))
  })
  if (operation.id !== 'discovery') parameters.push({ name: 'X-Active-Contract-Version', in: 'header', required: true, schema: { type: 'string', const: '1' } })
  const mutation = !['GET', 'HEAD'].includes(operation.method)
  if (mutation) parameters.push({ name: 'Idempotency-Key', in: 'header', required: true, schema: { type: 'string', minLength: 1 } })
  const legal = operation.id.startsWith('legal.')
  const item = { operationId: operation.id, parameters, responses: { [operation.success.status]: { description: 'Success', content: { [legal ? 'text/markdown' : 'application/json']: { schema: { $ref: `#/components/schemas/${key}_response` } } } }, default: { description: 'Active error', content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } } } } }
  if (operation.id !== 'discovery' && !legal) item.description = 'Requires an Active bearer access token or a same-origin web session with CSRF protection.'
  if (request.body._def.type !== 'null') item.requestBody = { required: true, content: { 'application/json': { schema: { $ref: `#/components/schemas/${key}_body` } } } }
  ;(paths[path] ||= {})[operation.method.toLowerCase()] = item
  metadata[operation.id] = { method: operation.method, path, legal, mutation }
}
const doc = { openapi: '3.1.0', info: { title: 'Active API', version: '1' }, paths, components: { schemas } }
fs.writeFileSync('contracts/v1/openapi.json', JSON.stringify(doc, null, 2) + '\n')
fs.writeFileSync('packages/api-client/src/operations.json', JSON.stringify(metadata, null, 2) + '\n')
for (const name of ['request-contract.cjs', 'response-contract.cjs']) fs.copyFileSync(`contracts/v1/${name}`, `packages/api-client/src/${name}`)
execFileSync(process.execPath, ['node_modules/openapi-typescript/bin/cli.js', 'contracts/v1/openapi.json', '-o', 'packages/api-client/src/generated.ts'], { stdio: 'inherit' })
const mapping = Object.keys(metadata).map(id => {
  const key = id.replace(/\./g, '_')
  return `  '${id}': { body: components['schemas']['${key}_body']; query: components['schemas']['${key}_query']; path: components['schemas']['${key}_path']; response: components['schemas']['${key}_response'] }`
}).join('\n')
fs.writeFileSync('packages/api-client/src/operation-types.ts', `// Generated by scripts/generate-contract.cjs.\nimport type { components } from './generated'\nexport interface Operations {\n${mapping}\n}\n`)
