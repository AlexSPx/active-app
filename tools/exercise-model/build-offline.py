"""Bundle the current viewer and model into a single offline HTML file."""

import argparse
import base64
import hashlib
import os
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
mode = parser.add_mutually_exclusive_group()
mode.add_argument("--app", action="store_true", help="regenerate the app assets too")
mode.add_argument("--check", action="store_true", help="verify the committed app assets")
args = parser.parse_args()

root = Path(__file__).resolve().parent
viewer_licenses = (root / "VIEWER-LICENSES.txt").read_text(encoding="utf-8")
bundle = subprocess.check_output(
    [os.environ.get("ESBUILD", root / "node_modules/.bin/esbuild"), "viewer.mjs", "--bundle",
     "--format=esm", "--target=es2022", "--minify", "--legal-comments=inline",
     f"--banner:js=/*\n{viewer_licenses}*/"],
    cwd=root,
    text=True,
)
html = (root / "index.html").read_text(encoding="utf-8")
html = re.sub(r'<script type="importmap">.*?</script>\s*', "", html, flags=re.S)
html = re.sub(r'<link rel="stylesheet" href="https://fonts.googleapis.com/[^"]+">\n', "", html)
model = base64.b64encode((root / "anatomy.glb").read_bytes()).decode("ascii")
group_index = subprocess.check_output(["node", "build-group-index.mjs"], cwd=root, text=True)
group_index = group_index.replace("<", r"\u003c")
offline = (
    f'<script id="embedded-model" type="application/octet-stream">{model}</script>\n'
    f'<script id="exercise-group-index" type="application/json">{group_index}</script>\n'
    f'<script type="module">\n{bundle}\n</script>'
)
html, replaced = re.subn(r'<script type="module">.*?</script>', lambda _: offline, html, flags=re.S)
if replaced != 1:
    raise ValueError("Expected one module script in index.html")
if not args.check:
    output = root / "dist" / "exercise-animations.html"
    output.parent.mkdir(exist_ok=True)
    output.write_text(html, encoding="utf-8")
    print(output)

if args.app or args.check:
    app_output = root.parent.parent / "apps/client/assets/exercise-animations.html"
    notices = "\n".join(
        (root / name).read_text(encoding="utf-8")
        for name in ("CC-BY-SA-4.0.txt", "ICT-FaceKit-LICENSE.txt")
    )
    app_html = html.replace("</html>", f"<!--\n{notices}\n-->\n</html>").encode("utf-8")
    # Gradle's React Native bundle task tracks TypeScript inputs and skips HTML.
    app_reference = (
        f"// Generated by build-offline.py. HTML SHA-256: {hashlib.sha256(app_html).hexdigest()}\n"
        "export const exerciseDemoAsset: number = require('./exercise-animations.html')\n"
    ).encode("utf-8")
    for path, content in ((app_output, app_html), (app_output.with_suffix(".ts"), app_reference)):
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit(f"{path.name} is stale. Run python3 tools/exercise-model/build-offline.py --app.")
        else:
            path.write_bytes(content)
            print(path)
